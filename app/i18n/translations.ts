export const translations: Record<Language, Dict> = { en, de, es, fr, it };

function lookup(dict: Dict, key: string): string | string[] | undefined {
  const value = key.split(".").reduce<any>((acc, part) => (acc && typeof acc === "object" ? acc[part] : undefined), dict);
  return typeof value === "string" || Array.isArray(value) ? value : undefined;
}

export function getTranslator(lang: Language) {
  const dict = translations[lang] ?? translations.en;
  return function t(key: string, vars?: Record<string, string | number>): string {
    const value = lookup(dict, key) ?? lookup(translations.en, key);
    let str = typeof value === "string" ? value : key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return str;
  };
}

export function getTranslatedList(lang: Language, key: string): string[] {
  const dict = translations[lang] ?? translations.en;
  const value = lookup(dict, key) ?? lookup(translations.en, key);
  return Array.isArray(value) ? value : [];
}
